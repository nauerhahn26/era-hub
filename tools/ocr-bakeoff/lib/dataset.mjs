// Dataset assembly for the OCR bake-off.
//
// The dataset lives OUTSIDE this repo (it is photographs of copyrighted books plus
// family PII). This module only knows how to build and read it; nothing here ever
// writes page text into the era-hub tree.

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

export const FFMPEG = process.env.FFMPEG_BIN || '/home/claude/.local/bin/ffmpeg';
export const CONDITIONS = ['raw', 'raw2048', 'processed'];

/** Stable, filesystem-safe page id: "<slug>-p03". */
export function pageId(slug, index) {
  return `${slug}-p${String(index).padStart(2, '0')}`;
}

export function ensureDir(d) {
  fs.mkdirSync(d, { recursive: true });
  return d;
}

/**
 * The two derived reference counts. ONE definition, used by build-dataset and by the
 * amendments pass, so an amended page can never carry the pre-amendment word count
 * (which would silently mis-weight every micro rate that page contributes to).
 */
export function gtMetrics(gt) {
  const s = typeof gt === 'string' ? gt : '';
  return { gtChars: s.length, gtWords: s.trim() ? s.trim().split(/\s+/).length : 0 };
}

/** Long-edge downscale to 2048px, JPEG q≈85 (ffmpeg -q:v 4). Idempotent. */
export function downscale2048(src, dst) {
  if (fs.existsSync(dst) && fs.statSync(dst).size > 0) return { skipped: true, dst };
  ensureDir(path.dirname(dst));
  const vf = "scale='if(gt(iw,ih),2048,-2)':'if(gt(iw,ih),-2,2048)':flags=lanczos";
  const r = spawnSync(FFMPEG, ['-hide_banner', '-loglevel', 'error', '-y', '-i', src, '-vf', vf, '-q:v', '4', dst], {
    encoding: 'utf8',
  });
  if (r.status !== 0) throw new Error(`ffmpeg failed for ${path.basename(src)}: ${(r.stderr || '').trim()}`);
  return { skipped: false, dst };
}

/**
 * Build <out>/dataset.json + <out>/images/<id>.2048.jpg from the joined ground-truth
 * rows. raw/processed stay as absolute path references - we never copy the 500 MB set.
 */
export function buildDataset({ rowsPath, outDir, log = console.log }) {
  const rows = JSON.parse(fs.readFileSync(rowsPath, 'utf8'));
  ensureDir(outDir);
  const imagesDir = ensureDir(path.join(outDir, 'images'));

  const pages = [];
  const problems = [];
  let built = 0;
  let reused = 0;

  for (const row of rows) {
    const id = pageId(row.slug, row.index);
    for (const k of ['raw', 'processed']) {
      if (!row[k] || !fs.existsSync(row[k])) problems.push(`${id}: missing ${k}`);
    }
    const dst = path.join(imagesDir, `${id}.2048.jpg`);
    let ok = true;
    try {
      const r = downscale2048(row.raw, dst);
      r.skipped ? reused++ : built++;
    } catch (e) {
      ok = false;
      problems.push(`${id}: ${e.message}`);
    }
    const gt = typeof row.gt === 'string' ? row.gt : '';
    pages.push({
      id,
      slug: row.slug,
      index: row.index,
      gt,
      ...gtMetrics(gt),
      images: {
        raw: row.raw,
        processed: row.processed,
        raw2048: ok ? dst : null,
      },
      bytes: {
        raw: fs.existsSync(row.raw) ? fs.statSync(row.raw).size : null,
        processed: fs.existsSync(row.processed) ? fs.statSync(row.processed).size : null,
        raw2048: ok && fs.existsSync(dst) ? fs.statSync(dst).size : null,
      },
    });
    if ((built + reused) % 20 === 0) log(`  ... ${built + reused}/${rows.length} images ready`);
  }

  const books = {};
  for (const p of pages) books[p.slug] = (books[p.slug] || 0) + 1;

  const dataset = {
    version: 1,
    builtAt: new Date().toISOString(),
    rowsSource: rowsPath,
    conditions: CONDITIONS,
    count: pages.length,
    books,
    emptyGtPages: pages.filter((p) => p.gtWords === 0).map((p) => p.id),
    pages,
  };
  fs.writeFileSync(path.join(outDir, 'dataset.json'), JSON.stringify(dataset, null, 2));
  return { dataset, built, reused, problems };
}

export const AMENDMENTS_FILE = 'amendments.json';

/**
 * Apply `<dataset>/amendments.json` to an in-memory dataset.
 *
 * The reference text is good, not infallible - `score`'s "possible ground-truth errors"
 * list exists precisely because it flags pages where the models are right and we are
 * wrong. Correcting one by hand-editing dataset.json would be invisible (the file is
 * regenerated by build-dataset and nobody reviews a 120-page JSON diff), so corrections
 * live in a separate, small, reviewable file that carries a REASON per page and is
 * re-applied on every load.
 *
 * Shape:
 *   { "note": "<why this file exists>",
 *     "pages": { "<pageId>": { "gt": "<replacement text, may be empty>", "reason": "<short>" } } }
 *
 * An empty replacement is meaningful, not a deletion: the page keeps its images and
 * becomes a phantom-text canary (no reference words -> excluded from every micro and
 * macro rate, still counted in phantom pages / phantom words).
 *
 * An unknown page id THROWS. A typo in this file must not silently amend nothing and
 * leave a reader believing a correction was applied.
 *
 * VALIDATE-THEN-MUTATE, in two passes: the error says "nothing was amended", so nothing
 * may have been. A single loop would have mutated every entry before the bad one and
 * handed a caller that catches the throw a half-amended dataset the message calls
 * untouched. loadDataset drops the object on a throw, but applyAmendments is exported
 * and called directly.
 */
export function applyAmendments(dataset, amendments) {
  const entries = Object.entries(amendments?.pages ?? {});
  const byId = new Map(dataset.pages.map((p) => [p.id, p]));
  for (const [id, a] of entries) {
    if (!byId.has(id)) throw new Error(`${AMENDMENTS_FILE}: unknown page id "${id}" - nothing was amended`);
    if (typeof a?.gt !== 'string')
      throw new Error(`${AMENDMENTS_FILE}: page "${id}" has no string "gt" field - nothing was amended`);
  }
  const applied = [];
  for (const [id, a] of entries) {
    const page = byId.get(id);
    page.gt = a.gt;
    Object.assign(page, gtMetrics(a.gt));
    page.amended = true;
    page.amendmentReason = typeof a.reason === 'string' ? a.reason : null;
    applied.push(id);
  }
  // emptyGtPages is derived from the references, so it has to follow them.
  dataset.emptyGtPages = dataset.pages.filter((p) => p.gtWords === 0).map((p) => p.id);
  dataset.amendedPages = applied;
  dataset.amendmentsNote = amendments?.note ?? null;
  return { applied, count: applied.length, note: dataset.amendmentsNote };
}

/**
 * Read dataset.json and apply amendments.json if it exists. Every consumer (run,
 * score, probe-quota) goes through here, so no command can ever read an unamended
 * reference.
 */
export function loadDataset(outDir) {
  const dataset = JSON.parse(fs.readFileSync(path.join(outDir, 'dataset.json'), 'utf8'));
  const amFile = path.join(outDir, AMENDMENTS_FILE);
  const amendments = fs.existsSync(amFile) ? JSON.parse(fs.readFileSync(amFile, 'utf8')) : null;
  applyAmendments(dataset, amendments);
  return dataset;
}

/** Absolute image path for a page under one condition, or null. */
export function imageFor(page, condition) {
  const p = page.images?.[condition];
  return p && fs.existsSync(p) ? p : null;
}

/** Select pages: 'all' | a positive integer (first N, round-robin over books) | a book slug. */
export function selectPages(dataset, spec) {
  const all = dataset.pages;
  if (!spec || spec === 'all') return all;
  const n = Number(spec);
  if (Number.isInteger(n) && n > 0) {
    // Round-robin across books so a small smoke sample spans different books.
    const byBook = new Map();
    for (const p of all) {
      if (!byBook.has(p.slug)) byBook.set(p.slug, []);
      byBook.get(p.slug).push(p);
    }
    const lists = [...byBook.values()];
    const out = [];
    for (let i = 0; out.length < n; i++) {
      let progressed = false;
      for (const l of lists) {
        if (i < l.length && out.length < n) {
          out.push(l[i]);
          progressed = true;
        }
      }
      if (!progressed) break;
    }
    return out;
  }
  const bySlug = all.filter((p) => p.slug === spec);
  if (!bySlug.length) throw new Error(`--pages: no book slug or page count matches "${spec}"`);
  return bySlug;
}

export default {
  CONDITIONS,
  AMENDMENTS_FILE,
  pageId,
  gtMetrics,
  buildDataset,
  loadDataset,
  applyAmendments,
  imageFor,
  selectPages,
  downscale2048,
  ensureDir,
};
