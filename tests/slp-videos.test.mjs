import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createSlpVideos } = require('../slp-videos.js');

test('local library, folder refresh, recording separation and request boundaries', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'era-slp-'));
  const shared = path.join(dir, 'shared'); fs.mkdirSync(shared);
  const api = createSlpVideos({ dataDir: dir, localFolder: () => shared,
    serveMedia(req,res,root,name) { res.end(fs.readFileSync(path.join(root,name))); }, maxRecordingBytes: 32 });
  const server = http.createServer((req,res) => { if (!api.handle(req,res)) res.writeHead(404).end(); });
  await new Promise(r => server.listen(0,'127.0.0.1',r));
  t.after(async () => { server.closeAllConnections(); await new Promise(r=>server.close(r)); fs.rmSync(dir,{recursive:true,force:true}); });
  const base = `http://127.0.0.1:${server.address().port}/api/slp-videos`;
  const request = (url,options) => fetch(base+url,options);
  const list = async () => (await request('/library')).json();
  assert.deepEqual((await list()).videos, []);
  assert.equal((await request('/library?name=Yeah.mp4',{method:'PUT',body:'video',headers:{'Content-Type':'video/mp4'}})).status,201);
  let library = await list(); assert.equal(library.videos[0].title,'Yeah');
  assert.equal(await (await fetch(new URL(library.videos[0].url,base))).text(),'video');
  fs.writeFileSync(path.join(dir,'outside.mp4'),'private');
  fs.symlinkSync(path.join(dir,'outside.mp4'),path.join(dir,'slp-videos','library','escape.mp4'));
  assert.equal((await list()).videos.length,1,'symlink outside library is never listed');
  fs.mkdirSync(path.join(shared,'slp-videos'));
  fs.writeFileSync(path.join(shared,'slp-videos','No.mp4'),'shared clip');
  library = await list(); assert.equal(library.source,'shared'); assert.deepEqual(library.videos.map(v=>v.title).sort(),['No','Yeah']);
  fs.writeFileSync(path.join(shared,'slp-videos','New.webm'),'new clip');
  assert.equal((await list()).videos.length,3,'folder changes appear on refresh');
  const configured=path.join(dir,'selected'); fs.mkdirSync(configured); fs.writeFileSync(path.join(configured,'Practice.mp4'),'practice');
  assert.equal((await request('/config',{method:'PUT',body:JSON.stringify({folder:configured})})).status,200);
  assert.ok((await list()).videos.some(v=>v.title==='Practice')); 
  fs.rmSync(configured,{recursive:true});
  assert.equal((await list()).available,false,'missing configured folder is reported, never silently substituted');
  assert.equal((await request('/recordings',{method:'POST',headers:{'Content-Type':'video/webm'},body:'recording'})).status,201);
  const recordings = await (await request('/recordings')).json();
  assert.equal(recordings.recordings.length,1);
  assert.match(recordings.recordings[0].url,/recordings\//);
  assert.equal(await (await fetch(new URL(recordings.recordings[0].url,base))).text(),'recording');
  assert.equal((await request('/recordings',{method:'POST',headers:{'Content-Type':'video/webm'},body:'x'.repeat(33)})).status,413);
  assert.equal((await request('/recordings',{method:'POST',headers:{'Content-Type':'text/html'},body:'bad'})).status,415);
  assert.equal((await request('/recordings',{method:'POST',headers:{'Content-Type':'video/webm'},body:''})).status,400);
  assert.equal((await request('/library?name=..%2Fescape.mp4',{method:'PUT',body:'bad'})).status,400);
  assert.equal((await request('/library',{headers:{Origin:'https://untrusted.invalid'}})).status,403);
  const rejectedHost = await new Promise((resolve,reject) => { const req=http.get(base+'/library',{headers:{Host:'untrusted.invalid'}},res=>{res.resume();resolve(res.statusCode);});req.on('error',reject); });
  assert.equal(rejectedHost,403);
  assert.equal((await request('/config',{method:'PUT',body:'{'})).status,400);
  assert.equal(fs.readdirSync(path.join(dir,'slp-videos','recordings')).length,1,'failed uploads leave no partial files');
  assert.equal(fs.existsSync(path.join(shared,'recordings')),false,'recordings never enter shared content');
});
